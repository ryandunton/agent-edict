package agent

import (
	"bytes"
	"fmt"
	"path/filepath"
	"slices"
	"strings"

	"github.com/ryandunton/agent-edict/internal/compiler"
	"github.com/ryandunton/agent-edict/internal/platform"
)

func nativeProduct(name string) bool {
	return compiler.IsNativeProduct(name)
}

// hookProducts run the protected edict executable from a client hook.
var hookProducts = []string{"cursor", "antigravity", "windsurf", "cline"}

func (a *Agent) preflightNativeRuntime(pm *PolicyMap) error {
	if !slices.ContainsFunc(pm.ManagedAgents, func(name string) bool { return slices.Contains(hookProducts, name) }) {
		return nil
	}
	validator, ok := a.provider.(platform.HookRuntimeValidator)
	if !ok {
		return fmt.Errorf("platform cannot validate the required hook executable")
	}
	return validator.ValidateHookRuntime()
}

// registrationStatus reports managed products whose hooks each user enrolls.
func registrationStatus(pm *PolicyMap) string {
	var parts []string
	for _, name := range []string{"antigravity", "cline"} {
		if slices.Contains(pm.ManagedAgents, name) {
			parts = append(parts, name+"_requires_install-hook_per_user")
		}
	}
	if len(parts) == 0 {
		return ""
	}
	return strings.Join(append(parts, "registration_and_client_acceptance_not_verified"), "; ")
}

// NativeCapabilities recompiles the signed declaration and validates exact
// artifact bytes. Capability labels are generated by code, not trusted input.
func NativeCapabilities(snapshot, osName string, pm *PolicyMap) ([]compiler.NativeCapability, error) {
	var products []string
	for _, product := range pm.ManagedAgents {
		if nativeProduct(product) {
			products = append(products, product)
		}
	}
	return NativeCapabilitiesFor(snapshot, osName, pm.MachineProfile, products)
}

// NativeCapabilitiesFor validates one profile's native declaration for the
// given products and returns their capability labels.
func NativeCapabilitiesFor(snapshot, osName, profile string, products []string) ([]compiler.NativeCapability, error) {
	if len(products) == 0 {
		return nil, nil
	}
	declaration := filepath.Join(snapshot, "profiles", osName, profile+".native.yaml")
	if err := rejectSymlinkComponents(snapshot, declaration); err != nil {
		return nil, err
	}
	data, err := readRegularFile(declaration, 1024*1024)
	if err != nil {
		return nil, fmt.Errorf("required native policy declaration: %w", err)
	}
	p, err := compiler.DecodeNativePolicy(data)
	if err != nil {
		return nil, err
	}
	if p.Name != profile {
		return nil, fmt.Errorf("native declaration name %q differs from profile %q", p.Name, profile)
	}
	var capabilities []compiler.NativeCapability
	for _, product := range products {
		out, err := compiler.CompileNative(p, osName, product)
		if err != nil {
			return nil, err
		}
		for _, artifact := range out.Artifacts {
			filename := filepath.Join(snapshot, "profiles", osName, profile+"."+artifact.Extension)
			if err := rejectSymlinkComponents(snapshot, filename); err != nil {
				return nil, err
			}
			actual, err := readRegularFile(filename, maxMemberBytes)
			if err != nil {
				return nil, fmt.Errorf("required native artifact %s: %w", artifact.Extension, err)
			}
			if !bytes.Equal(actual, []byte(artifact.Content)) {
				return nil, fmt.Errorf("native artifact %s does not match its validated declaration", artifact.Extension)
			}
		}
		capabilities = append(capabilities, out.Capabilities...)
	}
	return capabilities, nil
}
